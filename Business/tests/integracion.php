function comprobar(bool $valor, string $mensaje): void {
    global $checks;
    if (!$valor) throw new RuntimeException($mensaje);
    $checks++;
}
function api(string $method, string $path, mixed $data = null, ?string $token = null, int $status = 200, array $options = []): array {
    global $http, $checks;
    if ($data !== null) $options['json'] = $data;
    if ($token) $options['headers']['Authorization'] = 'Bearer ' . $token;
    $response = $http->request($method, $path, $options);
    $body = (string) $response->getBody();
    $decoded = str_starts_with($response->getHeaderLine('Content-Type'), 'application/json') ? json_decode($body, true, 512, JSON_THROW_ON_ERROR) : [];
    if ($response->getStatusCode() !== $status) throw new RuntimeException("$method $path: se esperaba $status, se recibió " . $response->getStatusCode() . '. ' . ($decoded['error'] ?? 'Respuesta sin detalle de error.'));
    $checks++;
    return ['body' => $decoded, 'response' => $response, 'raw' => $body];
}
